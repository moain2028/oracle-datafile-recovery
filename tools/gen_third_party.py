#!/usr/bin/env python3
"""Generate THIRD_PARTY_LICENSES.txt for the shipped binaries (odr, odr-corrupt).

Lists every crate that is compiled into odr / odr-corrupt on ANY target (Windows
and Linux), its licence expression, and the licence / notice texts the crate
itself ships, verbatim. Identical texts are printed once and referenced.

    python3 tools/gen_third_party.py            # rewrite THIRD_PARTY_LICENSES.txt
    python3 tools/gen_third_party.py --check    # exit 1 if the file is stale (CI)

Needs: cargo (the crates must be fetched: `cargo fetch --locked`).
Policy (which licences are allowed) is enforced separately by cargo-deny (deny.toml).
"""
import hashlib
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_LICENSES.txt"
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE|COPYRIGHT)([-_.].*)?$", re.I)


def run(*args: str) -> str:
    return subprocess.run(args, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def shipped_crates() -> set[tuple[str, str]]:
    out = run("cargo", "tree", "--locked", "-e", "normal", "--target", "all", "--prefix", "none",
              "-f", "{p}", "-p", "odr-cli", "-p", "odr-corrupt")
    crates = set()
    for line in out.splitlines():
        m = re.match(r"^(\S+) v(\S+)", line.strip())
        if m and not m.group(1).startswith("odr-"):
            crates.add((m.group(1), m.group(2)))
    return crates


def main() -> int:
    meta = json.loads(run("cargo", "metadata", "--locked", "--format-version", "1"))
    by_id = {(p["name"], p["version"]): p for p in meta["packages"]}
    texts: dict[str, tuple[int, str]] = {}  # sha -> (number, text)
    entries = []
    for name, ver in sorted(shipped_crates()):
        p = by_id[(name, ver)]
        d = pathlib.Path(p["manifest_path"]).parent
        files = sorted(f for f in d.iterdir() if f.is_file() and LICENSE_FILE.match(f.name))
        refs = []
        for f in files:
            t = f.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip()
            h = hashlib.sha256(t.encode()).hexdigest()
            if h not in texts:
                texts[h] = (len(texts) + 1, t)
            refs.append(f"{f.name} -> [T{texts[h][0]}]")
        entries.append((name, ver, p.get("license") or "(see files)", p.get("repository") or "", refs))

    lines = [
        "THIRD-PARTY SOFTWARE NOTICES — ODR (Oracle Datafile Recovery)",
        "=" * 62,
        "",
        "odr.exe / odr-corrupt.exe (and the Linux binaries) are proprietary software (see LICENSE).",
        "They include the open-source Rust crates listed below, each used under the licence shown.",
        "Where a crate offers a choice (\"MIT OR Apache-2.0\"), ODR uses it under the MIT licence;",
        "the full texts the crate ships are reproduced in part 2. None is copyleft (policy: deny.toml).",
        "The Rust standard library (MIT OR Apache-2.0, https://github.com/rust-lang/rust) is also included.",
        "",
        "Generated by tools/gen_third_party.py from Cargo.lock — do not edit by hand.",
        "",
        "PART 1 — CRATES",
        "-" * 15,
    ]
    for name, ver, lic, repo, refs in entries:
        lines.append(f"{name} {ver}  —  {lic}")
        if repo:
            lines.append(f"    {repo}")
        for r in refs:
            lines.append(f"    {r}")
    lines += ["", f"{len(entries)} crates.", "", "PART 2 — LICENCE AND NOTICE TEXTS", "-" * 33]
    for n, t in sorted(texts.values()):
        lines += ["", f"[T{n}]", "~" * (len(str(n)) + 3), t]
    body = "\n".join(lines) + "\n"

    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != body:
            print("THIRD_PARTY_LICENSES.txt is stale: run python3 tools/gen_third_party.py", file=sys.stderr)
            return 1
        print(f"THIRD_PARTY_LICENSES.txt up to date ({len(entries)} crates, {len(texts)} texts)")
        return 0
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT.name}: {len(entries)} crates, {len(texts)} distinct texts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
